/** Remote repository OpenAPI hydration preserves routes without trusting source URLs. */
import { describe, expect, it, vi } from 'vitest'

import { hydrateRemoteApiSpecs } from '../remote-api.js'
import type { MigrationBundle, MigrationFetcher } from '../types.js'

const SPEC_URL = 'https://specs.example.com/openapi.json'

function bundle(source = SPEC_URL): MigrationBundle {
  return {
    sourceUrl: 'https://github.com/example/docs',
    sourceKind: 'repository',
    platform: 'mintlify',
    pages: [{
      id: 'guide', navigationId: 'guide', title: 'Guide', description: '', keywords: [],
      body: '[List users](/api-reference/scim/list-users)', source: 'guide.mdx',
    }],
    assets: [],
    remoteApiSpecs: [{ url: source, tabLabel: 'API' }],
    docsConfig: { tabs: [{ tab: 'API', groups: [{ group: 'Overview', pages: ['guide'] }] }] },
    warnings: [{ code: 'unsupported-config', source, message: `The remote OpenAPI spec "${source}" requires a network download before this import is complete.` }],
    stats: { discovered: 1, imported: 1, skipped: 0 },
  }
}

const spec = JSON.stringify({
  openapi: '3.0.0',
  info: { title: 'Example', version: '1' },
  paths: { '/api/v1/scim/v2/Users': { get: { summary: 'List users', tags: ['SCIM'], responses: { 200: { description: 'OK' } } } } },
})

describe('remote OpenAPI hydration', () => {
  it('downloads a configured spec, enables generated navigation, and redirects known source links', async () => {
    const fetcher: MigrationFetcher = vi.fn(async (url) => ({ finalUrl: url, body: spec, contentType: 'application/json' }))
    const result = await hydrateRemoteApiSpecs(bundle(), fetcher)
    expect(fetcher).toHaveBeenCalledOnce()
    expect(result.assets).toHaveLength(1)
    expect(result.assets[0].path).toMatch(/^openapi\/openapi-[0-9a-f]{12}\.json$/)
    expect(result.assets[0].projectRelative).toBe(true)
    expect(result.docsConfig.tabs[0].api).toEqual({ source: result.assets[0].path })
    expect(result.docsConfig.redirects).toContainEqual({
      source: '/api-reference/scim/list-users',
      destination: '/api/default/api/v1/scim/v2/users/get',
      permanent: false,
    })
    expect(result.warnings).toEqual([])
  })

  it('points pages that name the spec by URL at the downloaded copy', async () => {
    const fetcher: MigrationFetcher = vi.fn(async (url) => ({ finalUrl: url, body: spec, contentType: 'application/json' }))
    const input = bundle()
    input.pages.push({ id: 'op', navigationId: 'op', title: 'Op', description: '', keywords: [], body: '', source: 'op.mdx', openapi: `${SPEC_URL} GET /api/v1/scim/v2/Users` })
    const result = await hydrateRemoteApiSpecs(input, fetcher)
    expect(result.pages[1].openapi).toBe(`${result.assets[0].path} GET /api/v1/scim/v2/Users`)
    expect(input.pages[1].openapi).toBe(`${SPEC_URL} GET /api/v1/scim/v2/Users`)
  })

  it('saves an extensionless URL by the format of its content', async () => {
    const extensionless = 'https://specs.example.com/unkey/openapi-with-code-samples'
    const yamlSpec = [
      '# Code generated by a spec generator',
      'openapi: 3.1.0',
      'info:',
      '  title: Example',
      '  version: "1"',
      'paths:',
      '  /api/v1/scim/v2/Users:',
      '    get:',
      '      summary: List users',
      '      tags: [SCIM]',
      '',
    ].join('\n')
    const input = bundle(extensionless)
    input.pages.push({ id: 'op', navigationId: 'op', title: 'Op', description: '', keywords: [], body: '', source: 'op.mdx', openapi: `${extensionless} GET /api/v1/scim/v2/Users` })

    const asYaml = await hydrateRemoteApiSpecs(input, async (url) => ({ finalUrl: url, body: yamlSpec, contentType: 'application/yaml' }))
    expect(asYaml.assets).toHaveLength(1)
    expect(asYaml.assets[0].path).toMatch(/^openapi\/openapi-[0-9a-f]{12}\.yaml$/)
    expect(asYaml.docsConfig.tabs[0].api).toEqual({ source: asYaml.assets[0].path })
    expect(asYaml.pages[1].openapi).toBe(`${asYaml.assets[0].path} GET /api/v1/scim/v2/Users`)
    expect(asYaml.docsConfig.redirects).toContainEqual({
      source: '/api-reference/scim/list-users',
      destination: '/api/default/api/v1/scim/v2/users/get',
      permanent: false,
    })
    expect(asYaml.warnings).toEqual([])

    const asJson = await hydrateRemoteApiSpecs(bundle(extensionless), async (url) => ({ finalUrl: url, body: spec, contentType: 'application/json' }))
    expect(asJson.assets[0].path).toMatch(/^openapi\/openapi-[0-9a-f]{12}\.json$/)
    expect(asJson.docsConfig.tabs[0].api).toEqual({ source: asJson.assets[0].path })
  })

  it('keeps a visible failure when an insecure or private host is configured', async () => {
    const fetcher: MigrationFetcher = vi.fn(async (url) => ({ finalUrl: url, body: spec, contentType: 'application/json' }))
    for (const source of ['http://specs.example.com/openapi.json', 'https://127.0.0.1/openapi.json']) {
      const result = await hydrateRemoteApiSpecs(bundle(source), fetcher)
      expect(result.assets).toEqual([])
      expect(result.warnings.some((warning) => warning.code === 'fetch-failed')).toBe(true)
    }
    expect(fetcher).not.toHaveBeenCalled()
  })

  it('does not redirect a linked URL that is a page of the site, and does not warn about it', async () => {
    const input = bundle()
    input.pages.push({ id: 'api-reference/scim/list-users', navigationId: 'api-reference/scim/list-users', title: 'List users', description: '', keywords: [], body: '', source: 'list-users.mdx' })
    const result = await hydrateRemoteApiSpecs(input, async (url) => ({ finalUrl: url, body: spec, contentType: 'application/json' }))
    expect(result.docsConfig.redirects).toBeUndefined()
    expect(result.warnings).toEqual([])
  })

  it('does not guess a redirect when operation labels collide', async () => {
    const duplicate = JSON.stringify({
      openapi: '3.0.0', info: { title: 'Example', version: '1' },
      paths: {
        '/users': { get: { summary: 'List users', tags: ['SCIM'] } },
        '/accounts': { get: { summary: 'List users', tags: ['SCIM'] } },
      },
    })
    const result = await hydrateRemoteApiSpecs(bundle(), async (url) => ({ finalUrl: url, body: duplicate, contentType: 'application/json' }))
    expect(result.assets).toHaveLength(1)
    expect(result.docsConfig.redirects).toBeUndefined()
  })
})

const MOUNTED_URL = 'https://specs.example.com/mounted.json'

/** Two products serving one spec: operations are listed under each directory, as Mintlify's explicit navigation does. */
const mountedSpec = JSON.stringify({
  openapi: '3.1.0',
  info: { title: 'Example', version: '1' },
  paths: {
    '/v2/projects.createProject': { post: { summary: 'Create project', tags: ['projects'], operationId: 'projects.createProject' } },
    '/v2/projects.getProject': { post: { summary: 'Get project', tags: ['projects'], operationId: 'projects.getProject' } },
    '/v2/workspace.getUsage': { post: { summary: 'Get workspace usage', tags: ['workspace'], operationId: 'workspace.getUsage' } },
    '/v2/identities.createIdentity': { post: { summary: 'Create Identity', tags: ['identities'], operationId: 'identities.createIdentity' } },
  },
})

function mountedBundle(): MigrationBundle {
  const page = (id: string, body = ''): MigrationBundle['pages'][number] => ({ id, navigationId: id, title: id, description: '', keywords: [], body, source: `${id}.mdx` })
  return {
    sourceUrl: 'https://github.com/example/docs',
    sourceKind: 'repository',
    platform: 'mintlify',
    pages: [
      page('guide', [
        '[create](/compute/api-reference/projects/create-project)',
        '[old](/api-reference/projects/create-project)',
        '[cli](/api-management/cli/identities/create-identity)',
      ].join('\n')),
      page('api-management/cli/identities/create-identity'),
    ],
    assets: [],
    remoteApiSpecs: [{
      url: MOUNTED_URL,
      tabLabel: 'API reference',
      directories: [
        { directory: 'compute/api-reference', operations: ['POST /v2/projects.getProject', 'POST /v2/projects.createProject'] },
        { directory: 'platform/api-reference', operations: ['POST /v2/projects.createProject', 'POST /v2/identities.createIdentity'] },
      ],
    }],
    docsConfig: {
      tabs: [{ tab: 'Guides', pages: ['guide'] }],
      redirects: [{ source: '/api-reference/projects/create-project', destination: '/compute/api-reference/projects/create-project' }],
    },
    warnings: [{ code: 'unsupported-config', source: MOUNTED_URL, message: `The remote OpenAPI spec "${MOUNTED_URL}" (tab "API reference") requires a network download before this import is complete.` }],
    stats: { discovered: 2, imported: 2, skipped: 0 },
  }
}

describe('remote OpenAPI spec mounted under Mintlify directories', () => {
  const fetcher: MigrationFetcher = async (url) => ({ finalUrl: url, body: mountedSpec, contentType: 'application/json' })

  it('redirects every listed endpoint URL under each directory to its endpoint page', async () => {
    const result = await hydrateRemoteApiSpecs(mountedBundle(), fetcher)
    const redirects = new Map((result.docsConfig.redirects ?? []).map((redirect) => [redirect.source, redirect.destination]))
    expect(redirects.get('/compute/api-reference/projects/create-project')).toBe('/api/default/v2/projects-createproject/post')
    expect(redirects.get('/compute/api-reference/projects/get-project')).toBe('/api/default/v2/projects-getproject/post')
    expect(redirects.get('/platform/api-reference/projects/create-project')).toBe('/api/default/v2/projects-createproject/post')
    expect(redirects.get('/platform/api-reference/identities/create-identity')).toBe('/api/default/v2/identities-createidentity/post')
  })

  it('redirects only the operations a directory lists', async () => {
    const result = await hydrateRemoteApiSpecs(mountedBundle(), fetcher)
    const sources = (result.docsConfig.redirects ?? []).map((redirect) => redirect.source)
    expect(sources.filter((source) => source.includes('workspace'))).toEqual([])
    expect(sources).not.toContain('/compute/api-reference/identities/create-identity')
  })

  it('sends a bare tag URL to the first operation that directory lists for the tag', async () => {
    const result = await hydrateRemoteApiSpecs(mountedBundle(), fetcher)
    const redirects = new Map((result.docsConfig.redirects ?? []).map((redirect) => [redirect.source, redirect.destination]))
    expect(redirects.get('/compute/api-reference/projects')).toBe('/api/default/v2/projects-getproject/post')
    expect(redirects.get('/platform/api-reference/projects')).toBe('/api/default/v2/projects-createproject/post')
  })

  it('points an authored redirect that targets an endpoint URL straight at the endpoint page', async () => {
    const result = await hydrateRemoteApiSpecs(mountedBundle(), fetcher)
    expect(result.docsConfig.redirects).toContainEqual({ source: '/api-reference/projects/create-project', destination: '/api/default/v2/projects-createproject/post' })
  })

  it('rewrites body links to endpoint URLs', async () => {
    const result = await hydrateRemoteApiSpecs(mountedBundle(), fetcher)
    expect(result.pages[0].body).toContain('[create](/api/default/v2/projects-createproject/post)')
  })

  it('creates no redirect over a page of the site and says nothing about it', async () => {
    const input = mountedBundle()
    const result = await hydrateRemoteApiSpecs(input, fetcher)
    const sources = (result.docsConfig.redirects ?? []).map((redirect) => redirect.source)
    // The CLI page shares its last two segments with the identities endpoint, but it is not that endpoint.
    expect(sources).not.toContain('/api-management/cli/identities/create-identity')
    expect(result.warnings).toEqual([])

    input.pages.push({ id: 'compute/api-reference/projects/create-project', navigationId: 'compute/api-reference/projects/create-project', title: 'Own page', description: '', keywords: [], body: '', source: 'own.mdx' })
    const withPage = await hydrateRemoteApiSpecs(input, fetcher)
    expect((withPage.docsConfig.redirects ?? []).map((redirect) => redirect.source)).not.toContain('/compute/api-reference/projects/create-project')
    expect(withPage.warnings).toEqual([])
  })
})

describe('remote OpenAPI spec endpoint redirects only reach published endpoints', () => {
  const hiddenSpec = JSON.stringify({
    openapi: '3.1.0',
    info: { title: 'Example', version: '1' },
    paths: {
      '/v2/keys.create': { post: { summary: 'Create key', tags: ['keys'], operationId: 'keys.create' } },
      '/v2/keys.hide': { post: { summary: 'Hide key', tags: ['keys'], 'x-hidden': true } },
      '/v2/keys.exclude': { post: { summary: 'Exclude key', tags: ['keys'], 'x-excluded': true } },
      '/v2/keys.internal': { 'x-hidden': true, post: { summary: 'Internal key', tags: ['keys'] } },
    },
  })
  const listed = ['POST /v2/keys.create', 'POST /v2/keys.hide', 'POST /v2/keys.exclude', 'POST /v2/keys.internal']

  it.each([
    ['listed in docs.json', listed],
    ['generated for every operation', undefined],
  ])('creates no redirect to an operation the published spec withholds: %s', async (_name, operations) => {
    const input = mountedBundle()
    input.pages = [input.pages[0]]
    input.docsConfig = { tabs: input.docsConfig.tabs }
    input.remoteApiSpecs = [{ url: MOUNTED_URL, tabLabel: 'API reference', directories: [{ directory: 'ref', ...(operations ? { operations } : {}) }] }]
    const result = await hydrateRemoteApiSpecs(input, async (url) => ({ finalUrl: url, body: hiddenSpec, contentType: 'application/json' }))
    const sources = (result.docsConfig.redirects ?? []).map((redirect) => redirect.source)
    expect(sources).toContain('/ref/keys/create-key')
    expect(sources.filter((source) => /hide|exclude|internal/.test(source))).toEqual([])
  })
})

describe('remote OpenAPI spec bodies', () => {
  const body = JSON.stringify({ openapi: '3.1.0', info: { title: 'Example', version: '1' }, paths: { '/v2/a': { post: { summary: 'Make a', tags: ['things'] } } } })
  const hydrate = (content: string | Buffer) => {
    const input = mountedBundle()
    input.docsConfig = { tabs: input.docsConfig.tabs }
    input.remoteApiSpecs = [{ url: MOUNTED_URL, tabLabel: 'API reference', directories: [{ directory: 'ref' }] }]
    return hydrateRemoteApiSpecs(input, async (url) => ({ finalUrl: url, body: content as never, contentType: 'application/json' }))
  }

  it('imports a JSON spec that starts with a byte order mark, saved without it', async () => {
    const result = await hydrate(Buffer.concat([Buffer.from([0xef, 0xbb, 0xbf]), Buffer.from(body)]))
    expect(result.warnings).toEqual([])
    expect(result.assets).toHaveLength(1)
    expect(result.assets[0].path).toMatch(/\.json$/)
    expect(() => JSON.parse(Buffer.from(result.assets[0].content).toString('utf8'))).not.toThrow()
    expect((result.docsConfig.redirects ?? []).map((redirect) => redirect.source)).toContain('/ref/things/make-a')
  })
})

describe('one remote OpenAPI spec bound to several tabs', () => {
  it('mounts each tab\'s directory once, with no warning and one copy of the spec', async () => {
    const input = mountedBundle()
    input.docsConfig = { tabs: input.docsConfig.tabs }
    input.remoteApiSpecs = [
      { url: MOUNTED_URL, tabLabel: 'Compute API', directories: [{ directory: 'compute/api-reference', operations: ['POST /v2/projects.createProject'] }] },
      { url: MOUNTED_URL, tabLabel: 'Platform API', directories: [{ directory: 'platform/api-reference', operations: ['POST /v2/projects.createProject'] }] },
    ]
    const result = await hydrateRemoteApiSpecs(input, async (url) => ({ finalUrl: url, body: mountedSpec, contentType: 'application/json' }))
    const sources = (result.docsConfig.redirects ?? []).map((redirect) => redirect.source)
    expect(sources).toContain('/compute/api-reference/projects/create-project')
    expect(sources).toContain('/platform/api-reference/projects/create-project')
    expect(result.warnings).toEqual([])
    expect(result.assets).toHaveLength(1)
    expect(result.docsConfig.tabs.filter((tab) => tab.api).map((tab) => tab.tab)).toEqual(['Compute API', 'Platform API'])
  })
})
